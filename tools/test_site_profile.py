"""Tests for site_profile.py: python3 -m unittest discover -s tools -p 'test_*.py'"""

import os
import subprocess
import sys
import tempfile
import unittest

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import site_profile as sp  # noqa: E402

TOOL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "site_profile.py")
CERN_LIKE = """# generated by scripts/setup.sh
SECURITY_PROXY_CONFIG_DIR='/srv/bits-services/config/security-proxy'
TLS_CERT_DIR='/srv/bits-services/secrets/tls'
GITLAB_API_URL='https://gitlab.cern.ch/api/v4'
BITS_FRONTEND_ORIGIN='https://bits-console.web.cern.ch'
BITS_WEBAUTHN_RP_ID='cern.ch'
BITS_WEBAUTHN_ORIGIN='https://bits-console.web.cern.ch'
BITS_WEBAUTHN_ORIGINS='https://bits-console.web.cern.ch,https://bits.cern.ch'
BITS_OIDC_ISSUER=''
BITS_OIDC_CI_AUDIENCE="https://bits.cern.ch"
BITS_OIDC_LOGIN_REDIRECT=https://bits.cern.ch/auth/callback  # the backend
BITS_LOGIN_RETURN_ALLOW='https://bits-console.web.cern.ch,https://bits.cern.ch'
BITS_FORGE_PROJECT='232657'
BITS_ADMINS_GROUP='bits/admins'
BITS_GITHUB_TOKEN='ghp_not_a_real_token'
BITS_ORCH_AUDIT_TOKEN='/run/secrets/audit_token'
RUNNER_SD_TOKEN=''
BITS_OIDC_TOKEN_URL='https://gitlab.cern.ch/oauth/token'
BITS_WEBAUTHN_CREDENTIALS='/data/creds.json'
CREDENTIALS_PROXY_CONFIG_DIR='./config/credentials-proxy'
VM_RETENTION='13'
"""


def without_secrets(env):
    return {k: v for k, v in env.items() if not sp.is_secret(k, v)}


class SiteProfileTest(unittest.TestCase):
    def round_trip(self, text):
        env = sp.parse_env(text)
        profile, secrets = sp.import_env(env)
        dumped = yaml.safe_load(yaml.safe_dump(profile))
        self.assertEqual(sp.derive_env(dumped), without_secrets(env))
        return env, profile, secrets

    def test_example_round_trips(self):
        with open(os.path.join(sp.DIR, ".env.example")) as f:
            _, profile, _ = self.round_trip(f.read())
        self.assertEqual(profile["overrides"], {})  # .env.example is as derived

    def test_derive_cern(self):
        self.assertEqual(sp.derive({
            "gitlab_url": "https://gitlab.cern.ch", "frontend_origin": "https://bits-console.web.cern.ch",
            "backend_url": "https://bits.cern.ch", "console_project": 232657,
            "admins_group": "bits/admins"}), {
            "GITLAB_API_URL": "https://gitlab.cern.ch/api/v4",
            "BITS_OIDC_ISSUER": "https://gitlab.cern.ch",
            "BITS_OIDC_JWKS_URL": "https://gitlab.cern.ch/oauth/discovery/keys",
            "BITS_FRONTEND_ORIGIN": "https://bits-console.web.cern.ch",
            "BITS_WEBAUTHN_ORIGIN": "https://bits-console.web.cern.ch",
            "BITS_LOGIN_RETURN_ALLOW": "https://bits-console.web.cern.ch",
            "BITS_WEBAUTHN_RP_ID": "cern.ch",
            "BITS_OIDC_CI_AUDIENCE": "https://bits.cern.ch",
            "BITS_OIDC_LOGIN_REDIRECT": "https://bits.cern.ch/auth/callback",
            "BITS_WEBAUTHN_ORIGINS": "https://bits-console.web.cern.ch,https://bits.cern.ch",
            "BITS_FORGE_PROJECT": "232657", "BITS_ADMINS_GROUP": "bits/admins"})

    def test_cern_like_round_trips(self):
        env, profile, secrets = self.round_trip(CERN_LIKE)
        self.assertEqual(profile["facts"], {
            "gitlab_url": "https://gitlab.cern.ch",
            "frontend_origin": "https://bits-console.web.cern.ch",
            "backend_url": "https://bits.cern.ch",
            "console_project": "232657", "admins_group": "bits/admins"})
        self.assertEqual(profile["overrides"], {
            "BITS_OIDC_ISSUER": "", "BITS_OIDC_JWKS_URL": None,
            "BITS_LOGIN_RETURN_ALLOW": "https://bits-console.web.cern.ch,https://bits.cern.ch"})
        self.assertEqual(secrets, ["BITS_GITHUB_TOKEN"])
        self.assertNotIn("ghp_not_a_real_token", yaml.safe_dump(profile))
        self.assertEqual(profile["env"]["BITS_ORCH_AUDIT_TOKEN"], "/run/secrets/audit_token")
        for key in ("BITS_OIDC_TOKEN_URL", "BITS_WEBAUTHN_CREDENTIALS", "CREDENTIALS_PROXY_CONFIG_DIR"):
            self.assertIn(key, profile["env"])
        self.assertNotIn("RUNNER_SD_TOKEN", profile["env"])  # secret-named, even empty

    def test_secret_never_printed(self):
        env = sp.parse_env(CERN_LIKE)
        profile, _ = sp.import_env(env)
        env.update(RUNNER_SD_TOKEN="/q8Zr+base64", BITS_ORCH_AUDIT_TOKEN="glpat-real")
        diffs, notes = sp.compare(profile, env)
        self.assertNotIn("q8Zr", repr((diffs, notes)))
        self.assertNotIn("glpat-real", repr((diffs, notes)))
        self.assertIn("secret in .env: RUNNER_SD_TOKEN (move it to service secrets)", notes)

    def test_profile_values(self):
        derived = sp.derive_env({"facts": {"gitlab_url": "https://gitlab.example.org/",
                                           "backend_url": "https://bits.example.org/"},
                                 "env": {"VM_RETENTION": 13}})
        self.assertEqual(derived["GITLAB_API_URL"], "https://gitlab.example.org/api/v4")
        self.assertEqual(derived["BITS_OIDC_LOGIN_REDIRECT"], "https://bits.example.org/auth/callback")
        self.assertEqual(derived["VM_RETENTION"], "13")
        for bad in ({"env": {"X": True}}, {"env": {"X": 1.1}}, {"env": {"X": None}},
                    {"facts": {"admins_group": ["a"]}}, ["not", "a", "mapping"], {"facts": ["a"]},
                    {"facts": {"gitlab_url": "https://g"}, "env": {"GITLAB_API_URL": "x"}}):
            with self.assertRaises(ValueError, msg=bad):
                sp.derive_env(bad)
        with self.assertRaises(ValueError) as e:
            sp.derive_env({"env": {"BITS_SIGN_PROXY_TOKEN": 1.5}})
        self.assertNotIn("1.5", str(e.exception))

    def test_parse_quoting(self):
        env = sp.parse_env("A='x #y'\nB=\"z\"\nC=w # note\nexport\tD=v\n# E=no\n"
                           "F='x' # note\nG=a=b\nH=w\t# tab\n")
        self.assertEqual(env, {"A": "x #y", "B": "z", "C": "w", "D": "v", "F": "x",
                               "G": "a=b", "H": "w"})
        for bad in ("A='it'\\''s'\n", "A='a'b\n"):
            with self.assertRaises(ValueError, msg=bad):
                sp.parse_env(bad)

    def test_render_refuses_quote_and_line_break(self):
        for value in ("it's", "a\nB=c", "a\rb"):
            with self.assertRaises(ValueError):
                sp.render_env({"A": value})

    def test_rp_id_must_fit_both_origins(self):
        profile = {"facts": {"frontend_origin": "https://console.example.org",
                             "backend_url": "https://bits.example.net"}}
        self.assertEqual(sp.check(profile), ["rp_id example.org is not a parent of bits.example.net"])
        profile["overrides"] = {"BITS_WEBAUTHN_RP_ID": None}
        self.assertEqual(sp.check(profile), ["rp_id is unset"])
        self.assertEqual(sp.check({"facts": {"frontend_origin": "https://bits-console.web.cern.ch",
                                             "backend_url": "https://bits.cern.ch"},
                                   "overrides": {"BITS_WEBAUTHN_RP_ID": "CERN.ch"}}), [])
        self.assertEqual(sp.check({"facts": {"frontend_origin": "https://localhost",
                                             "backend_url": "https://localhost"}}), [])

    def test_diff_reports_a_changed_derived_key(self):
        env = sp.parse_env(CERN_LIKE)
        profile, _ = sp.import_env(env)
        env["GITLAB_API_URL"] = "https://gitlab.example.org/api/v4"
        diffs, notes = sp.compare(profile, env)
        self.assertEqual(diffs, ["differs: GITLAB_API_URL: .env https://gitlab.example.org/api/v4, "
                                 "profile https://gitlab.cern.ch/api/v4"])
        self.assertIn("secret in .env: BITS_GITHUB_TOKEN (move it to service secrets)", notes)

    def test_command_line(self):
        with tempfile.TemporaryDirectory() as d:
            env_path, prof_path = os.path.join(d, ".env"), os.path.join(d, "site-profile.yaml")
            with open(env_path, "w") as f:
                f.write(CERN_LIKE)
            run = lambda *a: subprocess.run([sys.executable, TOOL, *a], capture_output=True, text=True)
            r = run("import", env_path)
            self.assertEqual(r.returncode, 0, r.stderr)
            self.assertIn("left out, a secret: BITS_GITHUB_TOKEN", r.stderr)
            with open(prof_path, "w") as f:
                f.write(r.stdout)
            self.assertEqual(run("diff", prof_path, env_path).returncode, 0)
            r = run("derive", prof_path)
            self.assertEqual(sp.parse_env(r.stdout), without_secrets(sp.parse_env(CERN_LIKE)))
            with open(env_path, "a") as f:
                f.write("BITS_FORGE_PROJECT='1'\n")
            self.assertEqual(run("diff", prof_path, env_path).returncode, 1)


if __name__ == "__main__":
    unittest.main()
